    @Test
    public void testUpdateRowsByCondition() {
        dataTemplate.insert("test_user", newUser("ur-1", "同组", 20, null));
        dataTemplate.insert("test_user", newUser("ur-2", "同组", 22, null));
        dataTemplate.insert("test_user", newUser("ur-3", "其他", 25, null));

        Map<String, Object> valMap = new HashMap<>();
        valMap.put("age", 99);

        Map<String, Object> paramMap = new HashMap<>();
        paramMap.put("name", "同组");

        int rows = dataTemplate.updateRows("test_user", valMap, paramMap);
        assertEquals(2, rows);

        Map<String, Object> r1 = queryTemplate.getMap("test_user", "ur-1");
        assertEquals(99, r1.get("AGE"));
        Map<String, Object> r3 = queryTemplate.getMap("test_user", "ur-3");
        assertEquals(25, r3.get("AGE"));
    }

    @Test
    public void testUpdateBatchMapByPrimaryKeys() {
        dataTemplate.insert("test_user", newUser("ub-1", "批量更新1", 20, null));
        dataTemplate.insert("test_user", newUser("ub-2", "批量更新2", 21, null));

        List<Map<String, Object>> updates = new ArrayList<>();
        Map<String, Object> u1 = new HashMap<>();
        u1.put("id", "ub-1");
        u1.put("age", 50);
        updates.add(u1);
        Map<String, Object> u2 = new HashMap<>();
        u2.put("id", "ub-2");
        u2.put("age", 51);
        updates.add(u2);

        int total = dataTemplate.update("test_user", updates);
        assertTrue("总更新行数应 >= 2", total >= 2);

        assertEquals(50, queryTemplate.getMap("test_user", "ub-1").get("AGE"));
        assertEquals(51, queryTemplate.getMap("test_user", "ub-2").get("AGE"));
    }

