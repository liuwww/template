    private DataSource dataSource;
    private DatabaseExecutor executor;
    private CoreDbContext dbContext;
    private IDataTemplate dataTemplate;
    private IQueryTemplate queryTemplate;

    @Before
    public void setUp() throws Exception {
        JdbcDataSource ds = new JdbcDataSource();
        ds.setURL("jdbc:h2:mem:test_dt_scenario;DB_CLOSE_DELAY=-1;MODE=MySQL");
        ds.setUser("sa");
        ds.setPassword("");
        this.dataSource = ds;
        this.executor = new JdbcDatabaseExecutor(dataSource);

        createTestTables();

        this.dbContext = new CoreDbContext();
        this.dbContext.addDataSource(dataSource);
        this.dbContext.setDatabaseExecutor(executor);
        this.dbContext.init();
        DbContext.setCurrentContext(this.dbContext);

        this.dataTemplate = dbContext.getDataTemplate();
        this.queryTemplate = dbContext.getQueryTemplate();
    }

    @After
    public void tearDown() throws Exception {
        DbContext.setCurrentContext(null);
        try (Connection conn = dataSource.getConnection();
                Statement stmt = conn.createStatement()) {
            stmt.execute("DELETE FROM test_user");
        } catch (Exception e) {
            // 忽略
        }
    }

    private void createTestTables() throws Exception {
        try (Connection conn = dataSource.getConnection();
                Statement stmt = conn.createStatement()) {
            stmt.execute("DROP TABLE IF EXISTS test_user");
            stmt.execute(
                    "CREATE TABLE test_user (" +
                            "id VARCHAR(32) PRIMARY KEY, " +
                            "name VARCHAR(100) NOT NULL, " +
                            "age INT, " +
                            "email VARCHAR(200), " +
                            "create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP" +
                            ")");
        }
    }

    private Map<String, Object> newUser(String id, String name, Integer age, String email) {
        Map<String, Object> user = new HashMap<>();
        user.put("id", id);
        user.put("name", name);
        user.put("age", age);
        user.put("email", email);
        return user;
    }

    // ==================== 插入场景 ====================

    @Test
    public void testInsertMapWithSpecifiedId() {
        Map<String, Object> user = newUser("ins-1", "张三", 25, "zhangsan@example.com");
        Row row = dataTemplate.insert("test_user", user);

        assertNotNull("Row 不能为 null", row);
        assertEquals("ins-1", row.getIdValue());

        Map<String, Object> result = queryTemplate.getMap("test_user", "ins-1");
        assertNotNull(result);
        assertEquals("张三", result.get("NAME"));
        assertEquals(25, result.get("AGE"));
    }

    @Test
    public void testInsertMapWithAutoGeneratedId() {
        Map<String, Object> user = new HashMap<>();
        user.put("name", "自动ID用户");
        user.put("age", 30);
        user.put("email", "auto@example.com");

        Row row = dataTemplate.insert("test_user", user);
        assertNotNull("Row 不能为 null", row);
        assertNotNull("应自动生成ID", row.getIdValue());
        assertFalse("ID不能为空字符串", row.getIdValue().isEmpty());

        Map<String, Object> result = queryTemplate.getMap("test_user", row.getIdValue());
        assertNotNull("应能查询到记录", result);
        assertEquals("自动ID用户", result.get("NAME"));
    }

    @Test
    public void testInsertBatchMapWithSpecifiedIds() {
        List<Map<String, Object>> list = new ArrayList<>();
        list.add(newUser("batch-1", "批量1", 21, "b1@example.com"));
        list.add(newUser("batch-2", "批量2", 22, "b2@example.com"));
        list.add(newUser("batch-3", "批量3", 23, "b3@example.com"));

        List<Row> rows = dataTemplate.insert("test_user", list);
        assertEquals("应返回3条Row", 3, rows.size());

        for (Row r : rows) {
            assertNotNull("每条Row的ID不应为null", r.getIdValue());
        }

        assertEquals(3L, queryTemplate.getCount("test_user", new HashMap<>()));
    }

