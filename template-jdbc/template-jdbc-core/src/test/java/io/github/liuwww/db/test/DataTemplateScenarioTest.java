    // ==================== 综合工作流 ====================

    @Test
    public void testFullWorkflowInsertQueryUpdateDelete() {
        // 1. 插入
        Map<String, Object> user = new HashMap<>();
        user.put("name", "工作流用户");
        user.put("age", 30);
        user.put("email", "wf@example.com");
        Row row = dataTemplate.insert("test_user", user);
        String id = row.getIdValue();
        assertNotNull(id);

        // 2. 查询验证
        Map<String, Object> result = queryTemplate.getMap("test_user", id);
        assertEquals("工作流用户", result.get("NAME"));

        // 3. 更新
        Map<String, Object> upd = new HashMap<>();
        upd.put("id", id);
        upd.put("age", 31);
        upd.put("name", "工作流用户更新");
        dataTemplate.update("test_user", upd);

        result = queryTemplate.getMap("test_user", id);
        assertEquals("工作流用户更新", result.get("NAME"));
        assertEquals(31, result.get("AGE"));

        // 4. 删除
        dataTemplate.delete("test_user", id);
        assertNull(queryTemplate.getMap("test_user", id));
    }

